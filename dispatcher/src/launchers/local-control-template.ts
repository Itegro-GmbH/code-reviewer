// How the local Dispatcher's launcher in Python (runner/src/code_reviewer_runner/factory_runner/firecracker/, #978) gets Control's
// `docker run` without a second implementation of the renderer. The arguments are rendered HERE, by `renderLocalControl` (the same code
// as the start request, #977), once with sentinel values for the four things that differ from job to job, and the sentinels are
// turned into markers (`{jobId}`, `{image}`, `{timeoutSeconds}`, `{agentMemoryMb}`). The result is checked in as
// runner/src/code_reviewer_runner/factory_runner/firecracker/control-run.template.json; a test here holds the file equal to what this
// module generates, and another proves that filling it gives exactly what the renderer renders for real values. The Python side fills the
// markers (`control_run.py`) and its tests feed the filled arguments to the same golden file (testdata/docker-run.local-control.golden.json).
// Regenerate it with:  node dispatcher/src/launchers/local-control-template-main.ts > <that file>
import { fileURLToPath } from "node:url";
import { renderLocalControl, LOCAL_IMAGE_REFERENCE } from "./local-control.ts";
import { SANDBOX_VCPUS, planForKind } from "./sandbox.ts";
import { workVolumeName } from "./container.ts";

export const CONTROL_TEMPLATE_PATH = fileURLToPath(
  new URL(
    "../../../runner/src/code_reviewer_runner/factory_runner/firecracker/control-run.template.json",
    import.meta.url,
  ),
);

// Values no real job has; they are rendered and replaced, never sent anywhere.
const SENTINEL_JOB = "jobidsentinel";
const SENTINEL_IMAGE = `sha256:${"0".repeat(64)}`;
const SENTINEL_TIMEOUT = 7654321;
const SENTINEL_AGENT_MEMORY = 7654322;

/** The sizes of the platform that can run an Implementer job: the others leave the agent too little memory (`sandbox_size_unsupported`). */
function implementerSizes(): number[] {
  return SANDBOX_VCPUS.filter((vcpus) => vcpus >= 2);
}

export interface ControlTemplate {
  arguments: string[];
  agentMemoryMb: Record<string, number>;
}

export interface ControlTemplateValues {
  jobId: string;
  image: string;
  timeoutSeconds: number;
  vcpus: number;
}

/** The template as the file holds it: the markers in the arguments and, per size, what the agent's container gets. */
export async function controlTemplateDocument(): Promise<string> {
  const plan = {
    ...planForKind("implementer", {}),
    agentMemoryMb: SENTINEL_AGENT_MEMORY,
  };
  const { args } = await renderLocalControl({
    spec: {
      appId: "template",
      appUrl: "https://app.invalid",
      jobId: SENTINEL_JOB,
      credential: "template-credential",
      kind: "implementer",
      timeoutSeconds: SENTINEL_TIMEOUT,
      config: {},
    },
    image: SENTINEL_IMAGE,
    plan,
    sysboxProof: "proven",
  });
  const marked = args.map((argument) =>
    argument
      .replaceAll(SENTINEL_JOB, "{jobId}")
      .replaceAll(SENTINEL_IMAGE, "{image}")
      .replaceAll(String(SENTINEL_TIMEOUT), "{timeoutSeconds}")
      .replaceAll(String(SENTINEL_AGENT_MEMORY), "{agentMemoryMb}"),
  );
  const agentMemoryMb: Record<string, number> = {};
  for (const vcpus of implementerSizes())
    agentMemoryMb[String(vcpus)] = planForKind("implementer", {
      launcher: { vcpus },
    }).agentMemoryMb;
  const document = {
    _comment:
      "Generated by dispatcher/src/launchers/local-control-template-main.ts from the local Control spec; never edit by hand (#978).",
    version: 1,
    arguments: marked,
    imageReference: LOCAL_IMAGE_REFERENCE,
    workVolumeName: workVolumeName(SENTINEL_JOB).replaceAll(
      SENTINEL_JOB,
      "{jobId}",
    ),
    agentMemoryMb,
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

/** The arguments of a job: the markers replaced. The Python launcher does the same (`control_run.py`). */
export function fillControlTemplate(
  template: ControlTemplate,
  values: ControlTemplateValues,
): string[] {
  const memory = template.agentMemoryMb[String(values.vcpus)];
  if (memory === undefined) throw new Error("no such size");
  return template.arguments.map((argument) =>
    argument
      .replaceAll("{jobId}", values.jobId)
      .replaceAll("{image}", values.image)
      .replaceAll("{timeoutSeconds}", String(values.timeoutSeconds))
      .replaceAll("{agentMemoryMb}", String(memory)),
  );
}
